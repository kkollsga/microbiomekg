def test_the_hit_threshold_decides_the_relationship_and_na_decides_neither():
    """`relation_for` is where the whole source's sign lives. The 55 real cells
    written `NA` are the case a `float(v) < THRESHOLD` written inline gets
    wrong twice over — it raises on the string, and a `try` wide enough to
    swallow that would file the pair as a non-hit, which is a measurement
    nobody made."""
    assert relation_for(HIT_THRESHOLD / 10) == RELATION_INHIBITS
    assert relation_for(HIT_THRESHOLD) == RELATION_NO_EFFECT
    assert relation_for(0.9) == RELATION_NO_EFFECT
    assert relation_for(None) is None


