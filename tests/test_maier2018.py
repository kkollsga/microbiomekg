    unmeasured = [
        r for r in table(csv_dir, "unresolved_maier2018.csv") if r["kind"] == "cell"
    ]
    assert len(unmeasured) == NOT_MEASURED
    assert unmeasured[0]["record_id"] == "Prestw-9998|NT5003"
    assert "NA" in unmeasured[0]["reason"]


