    assert "direction" not in GROWTH_CONTRACT
    assert "group_0_size" not in GROWTH_CONTRACT
    assert "sequencing_type" not in GROWTH_CONTRACT
    assert {"effect", "evidence_level", "publications"} <= set(GROWTH_CONTRACT)


