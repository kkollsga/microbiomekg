def test_an_atc_code_two_library_entries_claim_identifies_neither():
    """The Prestwick library screens stereoisomers and prodrug/active pairs as
    separate compounds, and an ATC code names the *substance* — so `(R)-` and
    `(S)-propranolol hydrochloride` share C07AA05. Joining both to the one
    ChEMBL node that code names is not a coarse answer but a wrong one: it
    attributes the R-enantiomer's measurement to the molecule ChEMBL keys as
    propranolol. Dropping the contested code is the same rule the ChEMBL side
    already applies to a code two ChEMBL nodes claim, and on the real file it
    is what takes the library from 1,180 distinct `Drug` nodes to 1,197 — one
    per entry, with no false merge."""
    from microbiomekg.preps import prep_maier2018 as prep

    contested = prep.contested_atc_codes(
        {
            "Prestw-1075": {"ATC codes": "C07AA05"},
            "Prestw-1081": {"ATC codes": "C07AA05"},
            "Prestw-45": {"ATC codes": "M01AE02"},
        }
    )
    assert contested == {"C07AA05": ["Prestw-1075", "Prestw-1081"]}
    # A code one entry carries twice is not contested — the same row, not two.
    assert (
        prep.contested_atc_codes({"Prestw-1": {"ATC codes": "C07AA05 C07AA05"}}) == {}
    )


