def test_an_override_is_written_only_where_the_row_confirms_it():
    """Five of the 76 strain names are corrected and two deliberately are not.
    Each correction is confirmed by something other than the spelling — a
    culture-collection number, an exhaustive edit-distance-1 search, or the
    binomial being a verbatim prefix — and the two that are not corrected have
    **two** NCBI candidates each with nothing in the row to choose between."""
    assert set(SPECIES_OVERRIDES) == {
        "pretovella copri",
        "bryantia formataxigens",
        "eubacterium biforme",
        "odoribacter splanchnius",
        "lactobacillus  reuteri cf48-3a",
    }
    assert all(key == key.casefold() for key in SPECIES_OVERRIDES)
    assert set(AMBIGUOUS_STRAINS) == {"bacteroides wh2", "bifidobacterium ruminatum"}
    # The two maps are disjoint: a name is either corrected or refused, never
    # both, and a name in neither resolves on its own.
    assert not set(SPECIES_OVERRIDES) & set(AMBIGUOUS_STRAINS)
    assert all(len(c) > 1 for c in AMBIGUOUS_STRAINS.values()), (
        "a name with one candidate would be an override, not a refusal"
    )
    # The column map is keyed on the screen's verbatim header, double space and
    # all, because a prefix rule would match seven B. fragilis rows at once.
    assert "Escherichia coli  K-12" in COLUMN_OVERRIDES


