def test_a_compound_the_other_screen_minted_reaches_that_node_not_a_second_one(
    graph, csv_dir, prep_output
):
    """**The reason `DEPENDS_ON` names `maier2018` and not only `chembl`.** 17 of
    the 271 real compounds reach a `Drug` node only because the growth screen
    minted one for them. Running first would mint a second node for each, and
    the split would be invisible: both nodes would have edges, both would look
    right, and D8's own question — does this drug inhibit gut bacteria *or* get
    metabolised by them — would return half an answer for every one of them."""
    node = one(
        graph,
        f"MATCH (d:Drug {{id: '{FICTITINE}'}}) "
        "RETURN d.source AS source, d.title AS name",
    )
    assert node["source"] == "maier2018", "the other screen still owns the node"
    both = one(
        graph,
        f"MATCH (d:Drug {{id: '{FICTITINE}'}}) "
        f"OPTIONAL MATCH (d)-[g:INHIBITS_GROWTH_OF|DOES_NOT_INHIBIT_GROWTH_OF]->() "
        f"OPTIONAL MATCH ()-[m:{RELATION_METABOLISES}|{RELATION_NO_METABOLISM}]->(d) "
        "RETURN count(DISTINCT g) AS growth, count(DISTINCT m) AS metabolism",
    )
    assert both["growth"] and both["metabolism"], (
        "one compound must carry both screens' edges, on one node"
    )
    assert len(table(csv_dir, "drug.csv")) == len(
        {r["drug_id"] for r in table(csv_dir, "drug.csv")}
    ), "drug.csv gained a duplicate identity"
    assert "joined to a node written by: chembl" in prep_output
    assert "maier2018" in prep_output.split("joined to a node written by:")[1]


