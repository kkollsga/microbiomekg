@pytest.mark.fixture
def test_the_fixture_keeps_the_real_workbook_shape():
    """The loader finds table 1's organisms between a header cell and the mutant
    section that follows them, table 2's drugs between its header and a blank
    row that a block of *column descriptions* follows, and table 3's five
    sub-columns by their labels rather than by counting. A tidied fixture would
    exercise none of that and would pass while the real file broke."""
    import openpyxl

    book = openpyxl.load_workbook(ZIMMERMANN_MINI / WORKBOOK, data_only=True)
    try:
        assert "Supplementary Table 1" in book.sheetnames
        strains = list(book["Supplementary Table 1"].iter_rows(values_only=True))
        drugs = list(book["Supplementary Table 2"].iter_rows(values_only=True))
        screen = list(book["Supplementary Table 3"].iter_rows(values_only=True))
        genes = list(book["Supplementary Table 13"].iter_rows(values_only=True))
    finally:
        book.close()

    # Table 1: a title, blanks, the header, a sub-heading with no phylum, the
    # organisms, then the mutants and plasmids that are not organisms.
    assert strains[0][0].startswith("Supplementary Table 1")
    assert strains[3][0] == "Name"
    assert any(
        row[0] == "Human gut bacteria tested for drug-metabolizing activity"
        and row[1] is None
        for row in strains
    )
    assert any(
        str(row[0] or "").startswith("Bacteroides thetaiotaomicron (Background")
        for row in strains
    )
    assert any(row[0] == "Plasmids" for row in strains)

    # Table 2: the data, a blank row, then the sheet describing its own columns.
    header_at = next(i for i, row in enumerate(drugs) if row[0] == "MOLENAME")
    blank_at = next(
        i
        for i, row in enumerate(drugs[header_at + 1 :], header_at + 1)
        if row[0] is None
    )
    assert any(row[0] == "MOLENAME" for row in drugs[blank_at:]), (
        "the column-description block is what makes the blank-row terminator "
        "load-bearing"
    )

    # Table 3: two header rows, the control among the strains, five sub-columns.
    block_at = next(i for i, row in enumerate(screen) if row[0] == "DrugName")
    labels = [c for c in screen[block_at] if c][1:]
    assert len(labels) == COLUMNS
    assert 0 < labels.index("Control pH 7 ") < len(labels) - 1, (
        "a control at either end could be found by position"
    )
    assert screen[block_at + 1][1] == "Drug adaptive FC threshold %"
    first = screen[block_at].index(labels[0])
    assert [str(screen[block_at + 1][first + k]).split()[0] for k in range(5)] == [
        "%",
        "%",
        "FC",
        "FC",
        "p(FDR)",
    ]
    assert len([r for r in screen[block_at + 2 :] if r[0]]) == DRUGS
    # The unmeasured cell is a *blank*, not a zero, which is what makes
    # `as_float` the right tool and a `float(cell) or 0` the wrong one.
    assert any(cell is None for row in screen[block_at + 2 :] for cell in row[2:])

    # Table 13: parent-drug columns interleaved with metabolite-mass columns.
    gene_at = next(i for i, row in enumerate(genes) if row[0] == "Gene")
    sub = genes[gene_at + 1]
    assert list(sub[:4]) == ["RefSeq Locus Tag", "PATRIC ID", "Product", "Protein ID"]
    assert sub.count("Parent drug") == 3
    assert any(isinstance(c, float) for c in sub[4:]), (
        "a metabolite-mass column is what the reader has to filter out"
    )
