def test_two_isolates_of_one_species_are_two_edges_on_one_taxon(graph):
    """The screen ran seven *B. fragilis* isolates and three
    *B. thetaiotaomicron* side by side. They are one taxon and independent
    measurements — C13's rule — and merging them would silently divide the
    evidence on that node."""
    result = one(
        graph,
        f"MATCH (t:Taxon {{id: {B_FRAGILIS}}})-[r:{RELATION_METABOLISES}|"
        f"{RELATION_NO_METABOLISM}]->(d:Drug {{id: '{VANCOMYCIN}'}}) "
        "RETURN count(r) AS edges, collect(DISTINCT r.screen_column) AS columns, "
        "count(DISTINCT r.strain) AS strains",
    )
    assert result["edges"] == 2
    assert sorted(result["columns"]) == [
        "Bacteroides fragilis DS-208",
        "Bacteroides fragilis NCTC9343",
    ]
    assert result["strains"] == 2, "the two isolates must stay distinguishable"


def test_the_column_override_is_what_reaches_the_strain_dictionary(graph, csv_dir):
    """The two sheets spell two of the 76 strains differently — table 3 writes
    the *E. coli* lineage where table 1 writes the Keio designation, and
    `formatexigens` where table 1 writes `formataxigens`. A prefix rule would
    catch the first and would also match `Bacteroides fragilis NCTC9343` against
    any of the seven *B. fragilis* rows, attaching one isolate's measurements to
    another's strain designation, so it is a closed two-entry map instead."""
    edge = one(
        graph,
        f"MATCH ()-[r:{RELATION_METABOLISES}|{RELATION_NO_METABOLISM}]->() "
        f"WHERE r.screen_column = '{E_COLI_OTHER_COLUMN}' "
        "RETURN DISTINCT r.strain_join AS route, r.strain AS strain, "
        "r.reported_name AS said, r.phylum AS phylum",
    )
    assert edge["route"] == "override"
    assert edge["strain"] == "BW25113", "the override reached the right row"
    assert edge["said"].strip() == "Escherichia coli"
    assert edge["phylum"] == "Proteobacteria"
    # No column went unjoined: an unmatched header is a ledger row, and there
    # are none of that shape here.
    assert not [
        r
        for r in ledger(csv_dir, "column")
        if "no supplementary-table-1 row" in r["reason"]
    ]


