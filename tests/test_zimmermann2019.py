def test_the_headline_check_refuses_to_write_when_it_stops_holding():
    """The gate that makes the line above worth printing, on both halves. A
    screen whose shape has changed cannot be checked against the published
    numbers at all, and a rule that no longer reproduces them is a rule we
    cannot use — writing 20,054 edges of unknown sign is the one failure this
    loader could never notice afterwards.

    The shape half matters as much as the count half: a gate that quietly
    stopped applying because a re-extraction dropped a column would be worse
    than no gate."""
    from microbiomekg.preps import prep_zimmermann2019 as prep

    screen = [
        {
            "drug": "A",
            "threshold": 20.0,
            "cells": [("Strain one", [50.0, 1.0, 0.5, 0.1, 0.001])],
        },
        {
            "drug": "B",
            "threshold": 20.0,
            "cells": [("Strain one", [1.0, 1.0, 0.01, 0.1, 0.9])],
        },
    ]
    columns = ["Strain one"]
    # One of the two drugs is metabolised, and the rule reproduces it.
    assert prep.check_headline(screen, columns, (2, 1, 1)) == 1
    with pytest.raises(SystemExit) as wrong_count:
        prep.check_headline(screen, columns, (2, 1, 2))
    assert "metabolised by at least one strain" in str(wrong_count.value)
    with pytest.raises(SystemExit) as wrong_shape:
        prep.check_headline(screen, columns, (271, 76, 176))
    assert "not 271 x 76" in str(wrong_shape.value)
    # And the real build's triple is the paper's, not something a caller chose.
    assert prep.PUBLISHED_MATRIX == (271, 76, 176)


