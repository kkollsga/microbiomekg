def test_an_ambiguous_strain_is_a_tombstone_naming_what_was_rejected(graph, csv_dir):
    """G2: nothing is dropped, and a refusal is not a shrug. NCBI holds
    `Bacteroides sp. WH2` **and** `Bacteroides cellulosilyticus WH2`, the row's
    reference is the bare token `WH2`, and nothing chooses between them. Picking
    one would attribute a whole 271-cell row to an organism nobody screened and
    no count would show it; refusing without saying what was refused would leave
    the next reader with a dead end."""
    tomb = one(
        graph,
        "MATCH (u:UnresolvedTaxon) WHERE u.raw_name = 'Bacteroides WH2' "
        "RETURN u.status AS status, u.reported_rank AS rank, "
        "u.candidates AS candidates",
    )
    assert tomb["status"] == "unresolved"
    assert tomb["rank"] == "strain-level isolate"
    assert sorted(tomb["candidates"]) == ["1268240", "311784"]
    assert (
        len([r for r in table(csv_dir, "unresolved_taxa.csv") if r["source"] == SOURCE])
        == UNRESOLVED_TAXA
    )
    strain_rows = ledger(csv_dir, "strain")
    assert len(strain_rows) == 1
    assert "Bacteroides sp. WH2 (311784)" in strain_rows[0]["detail"]
    assert "Bacteroides cellulosilyticus WH2 (1268240)" in strain_rows[0]["detail"]
    assert not rows(
        graph,
        "MATCH ()-[r]->() WHERE r.screen_column = 'Bacteroides WH2 WH2' RETURN r",
    )


