def test_the_edge_runs_from_the_bacterium_to_the_drug(graph):
    """Maier's screen says the drug changes the bug and its edges run
    `Drug -> Taxon`; this one says the bug changes the drug. Reversing either to
    make the pair symmetric would put the agent on the wrong end of half the
    edges — and `tests/test_acceptance.py` asserts that every `Drug -> Taxon`
    edge in the graph is the growth screen's, which only stays true because this
    source points the other way."""
    result = one(
        graph,
        f"MATCH (t:Taxon)-[r:{RELATION_METABOLISES}|{RELATION_NO_METABOLISM}]->"
        "(d:Drug) RETURN count(r) AS edges, count(DISTINCT d) AS drugs, "
        "count(DISTINCT t) AS taxa",
    )
    assert result["edges"] == EDGES
    assert result["drugs"] == DRUGS
    assert result["taxa"] == TAXA
    assert not rows(
        graph,
        f"MATCH (d:Drug)-[r:{RELATION_METABOLISES}|{RELATION_NO_METABOLISM}]->"
        "(t:Taxon) RETURN r",
    ), "a metabolism edge points from the drug to the bacterium"


def test_a_measured_non_hit_is_never_reachable_as_metabolism(graph):
    """The fixture says *E. coli K-12 does not metabolise paracetamol* — and the
    screen measured it, so that is a finding rather than an absence. Folding it
    into a property of a `METABOLISES` edge would make every
    `MATCH (t)-[:METABOLISES]->(d)` count it as metabolism, silently, for anyone
    who did not know to add a WHERE clause. It is Part D's own rule for this
    layer: two edge types, never one."""
    assert not rows(
        graph,
        f"MATCH (t:Taxon {{id: {E_COLI}}})-[r:{RELATION_METABOLISES}]->"
        f"(d:Drug {{id: '{ACETAMINOPHEN}'}}) "
        f"WHERE r.screen_column = '{E_COLI_OTHER_COLUMN}' RETURN r",
    )
    refutation = one(
        graph,
        f"MATCH (t:Taxon {{id: {E_COLI}}})-[r:{RELATION_NO_METABOLISM}]->"
        f"(d:Drug {{id: '{ACETAMINOPHEN}'}}) "
        f"WHERE r.screen_column = '{E_COLI_OTHER_COLUMN}' "
        "RETURN r.effect AS effect, r.source_relation AS relation, "
        "r.fdr_p_value AS p, r.percent_consumed AS consumed, "
        "r.drug_threshold_percent AS threshold, r.incubation_hours AS hours, "
        "r.replicates AS n",
    )
    assert refutation["effect"] == "not-metabolised"
    assert str(FDR_THRESHOLD) in refutation["relation"]
    # Depleted past the flat 20% floor and past significance in neither: this is
    # the cell that separates the published per-drug threshold from a floor.
    assert refutation["p"] > FDR_THRESHOLD
    assert refutation["consumed"] > 20.0
    assert refutation["threshold"] == 25.0
    # The negative is *bounded*, which is what makes it usable: not "nobody
    # looked", but "nothing at 12 h over four cultures".
    assert refutation["hours"] == 12.0 and refutation["n"] == 4


def test_both_populations_are_counted_and_neither_is_dropped(graph):
    """G4 applied to a screen: 7 hits and 40 measured non-hits in the fixture,
    2,575 and 17,479 in the real file. A loader that kept only the hits would
    look identical in every hit query and would have thrown away the half of the
    matrix that makes 'this strain was given this drug and did nothing to it'
    answerable at all."""
    counts = {
        rel: one(graph, f"MATCH ()-[r:{rel}]->() RETURN count(r) AS n")["n"]
        for rel in (RELATION_METABOLISES, RELATION_NO_METABOLISM)
    }
    assert counts[RELATION_METABOLISES] == METABOLISES
    assert counts[RELATION_NO_METABOLISM] == NO_METABOLISM
    effects = {
        r["effect"]
        for r in rows(
            graph,
            f"MATCH ()-[r:{RELATION_METABOLISES}|{RELATION_NO_METABOLISM}]->() "
            "RETURN DISTINCT r.effect AS effect",
        )
    }
    assert effects == {"metabolised", "not-metabolised"}
    # And the two screens' `effect` vocabularies do not overlap: a shared
    # `no-effect` token would make one WHERE clause mix "did not stop it
    # growing" with "did not touch the drug".
    growth = {
        r["effect"]
        for r in rows(
            graph,
            "MATCH ()-[r:INHIBITS_GROWTH_OF|DOES_NOT_INHIBIT_GROWTH_OF]->() "
            "RETURN DISTINCT r.effect AS effect",
        )
    }
    assert growth and not (growth & effects)


def test_an_abiotic_control_column_becomes_no_edge_and_one_ledger_row(
    graph, csv_dir, prep_output
):
    """The Maier lesson, in the other file: a column that reads exactly like a
    strain is not one. `Control pH 4` through `Control pH 7` sit among the
    strain columns with the same five sub-columns each, and on the real screen
    they produce 38 apparent hits between them. The fixture's single control is a
    hit for the first drug, so a loader that took the block structure at face
    value would write it."""
    assert not rows(
        graph,
        "MATCH ()-[r]->() WHERE r.screen_column STARTS WITH 'Control' RETURN r",
    )
    controls = ledger(csv_dir, "column")
    assert [r["record_id"] for r in controls] == ["Control pH 7"]
    assert "abiotic" in controls[0]["reason"]
    assert f"{CONTROL_CELLS:,} on an abiotic control column" in prep_output


def test_an_unmeasured_pair_is_neither_relationship_and_is_ledgered(graph, csv_dir):
    """All 20,596 measured cells of the real screen carry a number, which is
    worth knowing and is not worth trusting. A pair the screen did not measure
    is not a non-hit — calling it one invents a measurement, and it is exactly
    the direction that would look harmless."""
    for relationship in (RELATION_METABOLISES, RELATION_NO_METABOLISM):
        assert not rows(
            graph,
            f"MATCH (t:Taxon)-[r:{relationship}]->(d:Drug) "
            "WHERE r.reported_drug_name = 'AMPICILLIN SODIUM' "
            f"AND r.screen_column = '{E_COLI_OTHER_COLUMN}' RETURN r",
        )
    unmeasured = ledger(csv_dir, "cell")
    assert len(unmeasured) == NOT_MEASURED
    assert unmeasured[0]["record_id"] == f"AMPICILLIN SODIUM|{E_COLI_OTHER_COLUMN}"


