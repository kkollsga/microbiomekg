def test_the_metabolism_contract_is_a_rule_that_can_fail(graph):
    """Every field is written by this prep rather than read from upstream, so
    the rule *should* sit at zero — and a rule at zero is only worth having if it
    could move. The contract is the applicable subset: a monoculture metabolism
    screen has no direction, no cohort and no sequencing assay, and requiring
    those would report a permanent 100% meaning "this is not an abundance
    study"."""
    audit = {
        r["rule"]: r
        for r in rows(
            graph,
            "CALL ontology_audit() YIELD rule, violations, total "
            "RETURN rule, violations, total",
        )
    }
    for relationship in (RELATION_METABOLISES, RELATION_NO_METABOLISM):
        rule = audit[f"{relationship}.required_properties"]
        assert rule["total"] > 0, (
            f"{relationship} audits nothing — a gate that cannot fail"
        )
        assert rule["violations"] == 0, f"{relationship} violates its own contract"
    assert "direction" not in METABOLISM_CONTRACT
    assert "group_0_size" not in METABOLISM_CONTRACT
    assert "sequencing_type" not in METABOLISM_CONTRACT
    assert {"effect", "evidence_level", "publications"} <= set(METABOLISM_CONTRACT)


def test_every_screen_cell_is_an_edge_or_a_counted_reason(graph, csv_dir, prep_output):
    """Input cells = edges + unmeasured cells + the cells on an abiotic control
    column + the cells on a strain that reached no taxon. A silent drop cannot
    hide in the difference, and the two column-level terms are the ones a
    per-cell ledger would have buried: they are reported as counts instead."""
    edges = sum(
        one(
            graph,
            f"MATCH ()-[r:{rel}]->() WHERE r.primary_source = '{SOURCE}' "
            "RETURN count(r) AS n",
        )["n"]
        for rel in (RELATION_METABOLISES, RELATION_NO_METABOLISM)
    )
    assert edges == EDGES
    assert len(table(csv_dir, f"unresolved_{SOURCE}.csv")) == LEDGER_ROWS
    assert (
        f"not loaded: {NOT_MEASURED:,} cells the screen left a number out of, "
        f"{CONTROL_CELLS:,} on an abiotic control column, "
        f"{UNUSABLE_CELLS:,} on a strain that reached no taxon, "
        f"0 on a drug with no identifier"
    ) in prep_output
    assert EDGES + NOT_MEASURED + CONTROL_CELLS + UNUSABLE_CELLS == CELLS


