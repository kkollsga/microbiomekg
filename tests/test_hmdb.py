def test_a_rank_broader_than_a_family_reaches_the_ledger_not_an_edge(graph, csv_dir):
    """`Firmicutes` is why this is a correctness rule and not a tidiness one.
    NCBI files that exact string as a **synonym of 1783272 `Bacillati`, a
    kingdom** (the 2024 nomenclature change), while the phylum a reader means
    carries `firmicutes` only as a blast name, which NAME_CLASSES excludes. So
    a naive load does not write a vague edge — it writes a false one. The
    fixture's mini dump has no `Firmicutes` at all, so its phylum case is
    `Bacillota` (1239); both land in the ledger, by the two different routes."""
    ledger = {
        r["reported_name"]: r for r in table(csv_dir, "unresolved_production.csv")
    }
    broad = ledger["Bacillota"]
    assert broad["resolved_tax_id"] == "1239"
    assert broad["resolved_rank"] == "phylum"
    assert PRODUCTION_RANK_CEILING in broad["reason"]
    assert not rows(graph, "MATCH (t:Taxon {id: 1239})-[r:PRODUCES]->() RETURN r")
    # And the resolution is kept, so the decision is reversible rather than a
    # drop: a later phase can promote these without re-reading 6.5 GB.
    assert broad["microbe_path"].startswith(MICROBE_PATH)


def test_an_unresolvable_organism_is_a_tombstone_and_a_ledger_row(graph, csv_dir):
    """G2: nothing is dropped. A community (`Human gut microbiota`), a Gram
    stain and a string absent from names.dmp are all real HMDB terms and none
    of them is an organism NCBI has an id for."""
    tombstones = {
        r["raw_name"]: r
        for r in table(csv_dir, "unresolved_taxa.csv")
        if r["source"] == SOURCE
    }
    assert set(tombstones) == {
        "Firmicutes",
        "Human gut microbiota",
        "Gram-negative bacteria",
        "Akkermansia muciniphilia",
    }
    assert len(tombstones) == UNRESOLVED_TAXA
    for row in tombstones.values():
        assert row["status"] == "unresolved"
        assert row["n_signatures"] == "1"
    assert (
        one(
            graph,
            f"MATCH (u:UnresolvedTaxon) WHERE u.source = '{SOURCE}' RETURN count(u) AS n",
        )["n"]
        == UNRESOLVED_TAXA
    )


def test_the_ligature_typo_is_repaired_by_casefold_not_left_unresolved(graph, csv_dir):
    """**The one expectation the data refused.** `source-formats.md` §2 lists
    the U+FB01 ligature `Biﬁdobacterium` among the strings "expected to land in
    `UnresolvedTaxon`", and D5 repeats it. It does not: Python's
    ``str.casefold`` applies *full* case folding, which decomposes U+FB01 to
    ``fi``, so the reconciler's casefolded name index matches it to
    `Bifidobacterium` (1678) exactly as if it were spelled correctly.

    That is the right answer and a better one than the ledger — but it creates
    a failure the plan did not anticipate, because the same record carries the
    correctly spelled sibling too, and two terms resolving to one taxon are one
    annotation spelled twice, not two observations. The loader keeps one edge
    and files the loser with its reason."""
    assert "Biﬁdobacterium".casefold() == "bifidobacterium"
    edges = rows(
        graph,
        "MATCH (t:Taxon {id: 1678})-[r:PRODUCES]->(m:Metabolite {id: 'CHEBI:17272'}) "
        "RETURN r.reported_name AS reported",
    )
    assert len(edges) == 1, "the ligature and its sibling became two edges"
    assert edges[0]["reported"] == "Bifidobacterium", (
        "the tie-break must prefer the term that *is* the NCBI name it matched, "
        "not whichever the XML listed first"
    )
    dropped = [
        r
        for r in table(csv_dir, "unresolved_production.csv")
        if r["reported_name"] == "Biﬁdobacterium"
    ]
    assert len(dropped) == 1
    assert dropped[0]["resolved_tax_id"] == "1678"
    assert "already claimed" in dropped[0]["reason"]
    assert not any(
        r["raw_name"] == "Biﬁdobacterium" for r in table(csv_dir, "unresolved_taxa.csv")
    )


def test_a_species_term_suppresses_its_own_genus(graph):
    """A metabolite listing `Microbe/Faecalibacterium` and
    `Microbe/Faecalibacterium/Faecalibacterium prausnitzii` makes one claim at
    two levels of detail. Emitting both doubles the evidence for it and puts a
    genus row beside its own species row in D5's answer."""
    got = {
        (r["tax_id"], r["reported"])
        for r in rows(
            graph,
            "MATCH (t:Taxon)-[r:PRODUCES]->(m:Metabolite {id: 'CHEBI:17968'}) "
            "RETURN t.id AS tax_id, r.reported_name AS reported",
        )
    }
    assert got == {(853, "Faecalibacterium prausnitzii"), (841, "Roseburia")}


def test_a_misspelled_species_does_not_take_its_genus_down_with_it(graph, csv_dir):
    """The failure a plain "keep the leaf" rule produces. HMDB's species level
    carries `Citrobacter frundii`, `Akkermansia muciniphilia`,
    `Clostridium botulinium`; where such a typo is a genus's only child, the
    leaf rule drops a genus the source did name, silently. The genus is
    suppressed only when the species actually resolved."""
    result = one(
        graph,
        "MATCH (t:Taxon)-[r:PRODUCES]->(m:Metabolite {id: 'CHEBI:18089'}) "
        "RETURN t.id AS tax_id, r.reported_name AS reported, "
        "r.reported_rank AS reported_rank",
    )
    assert result["tax_id"] == 239934, "the genus edge was lost with its typo'd species"
    assert result["reported"] == "Akkermansia"
    assert result["reported_rank"] == "genus-level term"
    assert any(
        r["reported_name"] == "Akkermansia muciniphilia" and "unresolved" in r["reason"]
        for r in table(csv_dir, "unresolved_production.csv")
    )


def test_a_cross_kingdom_homonym_is_settled_by_the_microbial_context(graph):
    """`Bacillus` is a bacterial genus (1386) **and** a genus of stick insects
    (55087), and it is HMDB's single most common organism term — 13 metabolites
    in the real file, plus `Proteus` (a bacterium and an amphibian), `Serratia`,
    `Rhodococcus`, `Edwardsiella` and `Paracoccus`. `reconcile` answers
    `ambiguous` and returns the candidates rather than guessing, which is right:
    C2's warning is that `first-wins` invents facts. The context the *caller*
    has is that the term came from `Disposition/Source/Biological/Microbe`, so a
    stick insect is not merely less likely — it is wrong.

    Exactly one candidate under a microbial root, never the first: C3's point is
    that a kingdom heuristic cannot separate two bacteria, so
    `Lactobacillus plantarum` (1590 and 1385856) stays ambiguous."""
    result = one(
        graph,
        "MATCH (t:Taxon)-[r:PRODUCES]->(m:Metabolite {id: 'HMDB:HMDB0000032'}) "
        "RETURN t.id AS tax_id, r.resolution_status AS status, "
        "r.reported_name AS reported",
    )
    assert result == {
        "tax_id": 1386,
        "status": "kingdom-disambiguated",
        "reported": "Bacillus",
    }
    assert not rows(graph, "MATCH (t:Taxon {id: 55087})-[r:PRODUCES]->() RETURN r")


def test_a_placeholder_organism_resolves_and_is_flagged_not_dropped(graph):
    """G9: `Bacteroides sp.` is a real NCBI node (29523) meaning "some species
    of Bacteroides". It resolves verbatim and the *Taxon* carries the flag; a
    ranked query excludes it by that boolean, never by a name substring."""
    result = one(
        graph,
        "MATCH (t:Taxon)-[r:PRODUCES]->(m:Metabolite {id: 'CHEBI:16411'}) "
        "RETURN t.id AS tax_id, t.placeholder AS placeholder, "
        "r.reported_name AS reported",
    )
    assert result == {
        "tax_id": 29523,
        "placeholder": True,
        "reported": "Bacteroides sp.",
    }


def test_the_source_rank_claim_and_ncbis_rank_are_kept_apart(graph):
    """G5. `reported_rank` is HMDB's own level — and the point is that it is
    *not* a rank: its "genus" level holds genera, phyla, families, a class and
    two Gram stains. `original_rank` is what NCBI says. Folding them into one
    column makes the mixing invisible and the ceiling unauditable."""
    mixed = rows(
        graph,
        "MATCH ()-[r:PRODUCES]->() WHERE r.reported_rank = 'genus-level term' "
        "AND r.original_rank <> 'genus' "
        "RETURN r.reported_name AS reported, r.original_rank AS ncbi_rank",
    )
    assert {(r["reported"], r["ncbi_rank"]) for r in mixed} == {
        ("Bacteroides sp.", "species"),
        ("Clostridium symbiosum", "species"),
    }


