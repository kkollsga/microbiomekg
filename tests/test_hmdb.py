def test_the_production_contract_is_a_rule_that_can_fail(graph):
    """Unlike the association contract, every field here is written by this
    loader rather than read from upstream — so the rule *should* sit at zero,
    and a rule at zero for that reason is only worth having if it could move."""
    audit = {
        r["rule"]: r
        for r in rows(
            graph,
            "CALL ontology_audit() YIELD rule, violations, total RETURN rule, "
            "violations, total",
        )
    }
    rule = audit["PRODUCES.required_properties"]
    assert rule["total"] == PRODUCES_EDGES
    assert rule["violations"] == 0
    # And the contract is the applicable subset, not the association one: a
    # production claim has no direction, no assay and no cohort.
    assert "direction" not in PRODUCTION_CONTRACT
    assert "group_0_size" not in PRODUCTION_CONTRACT
    assert "evidence_level" in PRODUCTION_CONTRACT


def test_every_hmdb_produces_edge_still_carries_its_status(graph):
    """`hmdb_status` left `PRODUCTION_CONTRACT` when NJC19 became the second
    author of the `PRODUCES` table — a required property only one of two
    sources can write turns the other's every edge into a violation of a rule
    meant to read zero. The guarantee did not go anywhere, it moved here, which
    is where a source-specific field's guarantee belongs: the contract is what
    both authors owe, and this is what *this* author owes."""
    assert "hmdb_status" not in PRODUCTION_CONTRACT
    statuses = [
        r["status"]
        for r in rows(
            graph,
            "MATCH ()-[r:PRODUCES]->() WHERE r.primary_source = 'hmdb' "
            "RETURN r.hmdb_status AS status",
        )
    ]
    assert len(statuses) == PRODUCES_EDGES
    assert all(statuses), "an HMDB production edge with no detection status"
    assert set(statuses) <= {"expected", "predicted", "detected", "quantified"}


def test_no_rule_this_source_declares_audits_nothing(graph):
    """A rule with a zero denominator is a gate that cannot fail.

    Scoped to the relationships **these two sources add**, because the spine is
    always composed: this fixture loads no association source, so
    ``ASSOCIATED_WITH``'s rules sit at ``0 / 0`` here and would in any
    single-source build. That is a property of the fixture, not of the loader —
    ``scripts/build.py`` composes a partial ontology exactly so it is not a
    property of a real one."""
    totals = {
        r["rule"]: r["total"]
        for r in rows(
            graph, "CALL ontology_audit() YIELD rule, total RETURN rule, total"
        )
    }
    mine = {
        rule: n
        for rule, n in totals.items()
        if rule.split(".")[0] in ("PRODUCES", "IN_PATHWAY", "PART_OF_PATHWAY")
    }
    assert mine, "the audit reports no rule for this source's relationships at all"
    for rule, n in mine.items():
        assert n > 0, f"{rule} audits nothing"


def test_the_producing_taxa_are_all_cited_and_loaded(graph, csv_dir):
    """`cited_taxa.csv` drives which taxa the taxonomy build keeps; a source
    that did not contribute to it would have its edges point at nothing."""
    got = {
        r["tax_id"]
        for r in rows(
            graph, "MATCH (t:Taxon)-[:PRODUCES]->() RETURN DISTINCT t.id AS tax_id"
        )
    }
    assert got == PRODUCING_TAXA
    cited = {int(r["tax_id"]) for r in table(csv_dir, "cited_taxa.csv")}
    assert PRODUCING_TAXA <= cited
