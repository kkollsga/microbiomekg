"""HMDB: 578 production claims over 224 records, and how a naive load loses them.

The fixture (``tests/fixtures/hmdb_mini/``, generated by
``tests/fixtures/make_hmdb_mini.py``, which names every injected record) carries
one record per trap from ``docs/research/source-formats.md`` §2, and the loader
is measured against what each trap would silently do:

* a substring match on ``microb`` selects ``Antimicrobial agent`` — a drug that
  *kills* microbes — as a microbial metabolite;
* loading all 217,920 records puts a chemistry database in a microbiome graph,
  88.8% of it never observed in a sample;
* resolving HMDB's organism strings verbatim writes "a **kingdom** produces
  butyrate", because NCBI files ``Firmicutes`` as a synonym of ``Bacillati``;
* keeping only the deepest organism term loses the whole claim whenever the one
  species under a genus is misspelled, which HMDB's are;
* loading the disease layer creates one ``Disease`` node with 20,020 metabolite
  edges;
* reading ``<chebi_id/>`` straight writes the string ``"None"`` into the graph.

One of those expectations did not survive contact with the data, and the test
that records it is
:func:`test_the_ligature_typo_is_repaired_by_casefold_not_left_unresolved`.
"""

