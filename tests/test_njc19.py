def test_a_refutation_is_never_reachable_as_an_observation(graph):
    """The fixture's `Succinate` row says *Bacteroides thetaiotaomicron does
    not export succinate*. Folding it into a property of a `PRODUCES` edge
    would make every `MATCH (t)-[:PRODUCES]->(m)` count it as a production
    claim — silently, for anyone who did not know to add a WHERE clause."""
    succinate = one(
        graph, "MATCH (m:Metabolite {title: 'Succinic acid'}) RETURN m.id AS id"
    )["id"]
    assert not rows(
        graph,
        f"MATCH (t:Taxon {{id: 818}})-[r:PRODUCES]->(m:Metabolite {{id: '{succinate}'}}) "
        f"WHERE r.primary_source = '{SOURCE}' RETURN r",
    )
    refutation = one(
        graph,
        f"MATCH (t:Taxon {{id: 818}})-[r:NO_EXCHANGE_WITH]->(m:Metabolite "
        f"{{id: '{succinate}'}}) RETURN r.source_relation AS rel",
    )
    assert refutation["rel"] == "export-negative"


def test_every_negative_names_the_activity_it_refutes(graph):
    """`NO_EXCHANGE_WITH` is shared by all three activities, so without
    `source_relation` a refuted import and a refuted degradation are one
    undifferentiated edge."""
    relations = {
        r["rel"]
        for r in rows(
            graph,
            "MATCH ()-[r:NO_EXCHANGE_WITH]->() RETURN DISTINCT r.source_relation AS rel",
        )
    }
    assert relations <= {"import-negative", "export-negative", "degrade-negative"}
    assert one(graph, "MATCH ()-[r:NO_EXCHANGE_WITH]->() RETURN count(r) AS n")[
        "n"
    ] == (NO_EXCHANGE)


