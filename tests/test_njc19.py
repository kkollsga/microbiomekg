"""NJC19: the consumption edge, the negatives that must stay countable, and the
name join that decides whether D6 has an answer at all.

The fixture (``tests/fixtures/njc19_mini/``, generated by
``tests/fixtures/make_njc19_mini.py``, which names every row and its trap) is
loaded through the real preps and the real blueprint alongside HMDB's and
MiMeDB's, because three of the things worth asserting here are *joins* to what
those two wrote:

* ``Butyrate`` must reach HMDB's ``Butyric acid`` node. If it does not, the
  producers are on one node and the consumers on another and D6's MES —
  **2·P·C / (P + C)** — is 0 for both halves of every short-chain fatty acid in
  the graph, which looks exactly like "no source has this";
* ``Pectin`` must reach the node **MiMeDB** wrote, which is the entire
  measurable contribution MiMeDB makes to this graph;
* ``Mucin`` must be minted, because nothing holds it and a dropped compound
  would remove a degradation claim the source did curate.

And the two that are about not inventing anything: the 6 host cell types must
not become ``UnresolvedTaxon`` tombstones, and a refutation must not be
reachable by a query for an observation.
"""

