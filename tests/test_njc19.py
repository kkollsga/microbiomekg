def test_every_row_is_an_edge_or_a_counted_reason(graph, csv_dir, prep_output):
    """Input rows = edges + ledger rows + the one duplicate, with the combined
    row counted twice because it is two claims. A silent drop cannot hide in
    the difference."""
    edges = sum(
        one(
            graph,
            f"MATCH ()-[r:{rel}]->() WHERE r.primary_source = '{SOURCE}' "
            "RETURN count(r) AS n",
        )["n"]
        for rel in ("PRODUCES", "CONSUMES", "DEGRADES", "NO_EXCHANGE_WITH")
    )
    ledger = table(csv_dir, "unresolved_exchange.csv")
    assert len(ledger) == LEDGER_ROWS
    duplicate, combined = 1, 1
    assert edges + len(ledger) + duplicate - combined == DATA_ROWS
    assert f"read {DATA_ROWS} rows -> {EDGES} edges" in prep_output


