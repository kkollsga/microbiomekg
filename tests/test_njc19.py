def test_the_exchange_contract_is_a_rule_that_can_fail(graph):
    """Every field is written by this prep rather than read from upstream, so
    the rule *should* sit at zero — and a rule at zero is only worth having if
    it could move."""
    audit = {
        r["rule"]: r
        for r in rows(
            graph,
            "CALL ontology_audit() YIELD rule, violations, total "
            "RETURN rule, violations, total",
        )
    }
    for rel in ("PRODUCES", "CONSUMES", "DEGRADES", "NO_EXCHANGE_WITH"):
        rule = audit[f"{rel}.required_properties"]
        assert rule["total"] > 0, f"{rel} audits nothing — a gate that cannot fail"
        assert rule["violations"] == 0, f"{rel} violates its own contract"
    # And the contract is the applicable subset: an exchange claim has no
    # direction, no assay and no cohort.
    assert "direction" not in EXCHANGE_CONTRACT
    assert "group_0_size" not in EXCHANGE_CONTRACT
    assert {"evidence_level", "reported_name"} <= set(EXCHANGE_CONTRACT)


def test_hmdb_status_is_not_required_of_a_source_that_has_no_such_column(graph):
    """It was the ninth field of `PRODUCTION_CONTRACT` and could not survive a
    second author: NJC19 has no detection status, so a required `hmdb_status`
    would report every NJC19 edge as a violation of a rule meant to read zero —
    an audit number that means "a source landed", not "evidence is missing"."""
    assert "hmdb_status" not in EXCHANGE_CONTRACT
    for row in rows(
        graph,
        f"MATCH ()-[r:PRODUCES]->() WHERE r.primary_source = '{SOURCE}' "
        "RETURN DISTINCT r.hmdb_status AS status",
    ):
        assert not row["status"]


def test_every_exchanging_taxon_is_cited_and_loaded(graph, csv_dir):
    """`cited_taxa.csv` drives which taxa the taxonomy build keeps; a source
    that did not contribute to it would have its edges point at nothing."""
    got = {
        r["tax_id"]
        for r in rows(
            graph,
            "MATCH (t:Taxon)-[r]->(:Metabolite) "
            f"WHERE r.primary_source = '{SOURCE}' RETURN DISTINCT t.id AS tax_id",
        )
    }
    cited = {
        int(r["tax_id"])
        for r in table(csv_dir, "cited_taxa.csv")
        if r["source"] == SOURCE
    }
    assert got and got <= cited


def test_a_byte_identical_row_is_one_edge_not_two(graph):
    """A duplicate fact is not a second observation. The fixture repeats its
    first row verbatim; `dedupe_full` collapses it, and the *genuinely* parallel
    edges — a taxon and a compound from two different reference sets — survive
    because their `source_record_id` and references differ."""
    assert (
        one(
            graph,
            f"MATCH (t:Taxon {{id: 853}})-[r:PRODUCES]->(m:Metabolite {{id: '{BUTYRIC_ACID}'}}) "
            f"WHERE r.primary_source = '{SOURCE}' RETURN count(r) AS n",
        )["n"]
        == 1
    )


