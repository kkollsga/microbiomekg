def rows(graph, query):
    return list(graph.cypher(query))


def one(graph, query):
    result = rows(graph, query)
    assert result, f"query returned no rows:\n{query}"
    return result[0]


def table(csv_dir, name):
    with (csv_dir / name).open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


# --------------------------------------------------------------------------
# The finding: no association exists in the download
# --------------------------------------------------------------------------


def test_mimedb_writes_no_taxon_metabolite_edge_because_there_is_none(graph, prep_output):
    """**The headline assertion of this module, and it is a zero.**

    The two downloads are `SELECT * FROM microbes` and `SELECT * FROM
    metabolites`; the join between them is in neither, and the nearest thing to
    a relation in either is a `microbes.activity` column that says `Production
    (export)` **with no compound named anywhere on the row**. Deriving an edge
    from it would manufacture exactly the claim D5 asks for out of a field that
    does not make it. The fixture carries that row on purpose.

    A zero is only worth asserting if something could make it non-zero, and
    something could: this test fails the moment any relationship is declared
    for this source, which is the review gate on "MiMeDB finally has an edge
    list" being a deliberate change rather than an accident."""
    assert RELATIONSHIPS == {}
    for row in rows(
        graph, "MATCH ()-[r]->() RETURN DISTINCT r.primary_source AS source"
    ):
        assert row["source"] != SOURCE
    assert "PRODUCES edges from MiMeDB: 0" in prep_output


def test_the_organisms_are_read_reported_and_not_loaded(graph, prep_output):
    """The microbes table resolves almost perfectly — every row carries an NCBI
    taxid — and that is exactly the point: this source has the taxon side of
    D5's edge and nothing to attach it to. Reporting the number is what
    separates "MiMeDB does not close D5" from "MiMeDB has nothing"; loading it
    would put 2,174 unconnected `Taxon` nodes in the real graph."""
    assert f"microbes: {MICROBES} organisms, {MICROBES} with an NCBI taxid" in prep_output
    assert "promoted 1" in prep_output, "the strain-level row must promote to its species"
    # Not in cited_taxa.csv, so the taxonomy build keeps none of them for MiMeDB.
    assert not rows(
        graph,
        f"MATCH (t:Taxon)-[r]->() WHERE r.primary_source = '{SOURCE}' RETURN t",
    )


