def test_the_release_is_detected_from_the_columns_not_the_filename(graph, prep_output):
    """A file's name is an operator's claim; its header is the dump's. The four
    v2-only columns are what says "this is v2.0", so a v2 file dropped in under
    a v1 name — or the reverse — cannot make the graph lie about its provenance.
    The release rides on every node this source writes, because a graph that
    outlives this build report has to be able to answer which release it holds."""
    assert release_of(["id", "name", "microbe_relations"]) == "v2.0"
    assert release_of(["id", "name", "hmdb_id"]) == "v1.0"
    # The two tables grew different columns, so a header list built only from
    # the metabolites side reports every v2 microbes dump as v1.0.
    assert not set(V2_ONLY_COLUMNS) & set(V2_ONLY_MICROBE_COLUMNS)
    assert release_of(["id", "name", "basys2_id"]) == "v2.0"
    # `description` is new to the microbes table and has always been in the
    # metabolites one, so it must never be a release marker.
    assert "description" in V2_ONLY_MICROBE_COLUMNS
    assert release_of(["id", "name", "description", "hmdb_id"]) == "v1.0"
    assert "MiMeDB v2.0" in prep_output
    assert "(MiMeDB v2.0)" in prep_output, "the microbes report names its own release"
    releases = {
        r["release"]
        for r in rows(
            graph,
            f"MATCH (m:Metabolite) WHERE m.source = '{SOURCE}' "
            "RETURN DISTINCT m.mimedb_release AS release",
        )
    }
    assert releases == {"v2.0"}


def test_v1_still_loads_and_says_so(built_v1):
    """v2 is what a fresh clone should place, and v1 is what this project
    actually fetched in 2026-09 — the operator may have either. The fallback is
    a code path, so it is tested: the same rules select six of eleven records
    rather than seven of twelve, the four v2-only columns are absent rather than
    empty-by-accident, and the node says `v1.0`."""
    graph_v1, _csv_v1, out_v1 = built_v1
    assert "MiMeDB v1.0" in out_v1
    assert f"read {RECORDS_V1:,} metabolite records" in out_v1
    assert f"loaded {LOADED_V1:,} new Metabolite nodes" in out_v1
    assert (
        f"microbes: {MICROBES_V1} organisms, {MICROBES_V1} with an NCBI taxid" in out_v1
    )
    releases = {
        r["release"]
        for r in rows(
            graph_v1,
            f"MATCH (m:Metabolite) WHERE m.source = '{SOURCE}' "
            "RETURN DISTINCT m.mimedb_release AS release",
        )
    }
    assert releases == {"v1.0"}
    # v1 has no such column, so nothing may claim a count for it.
    for row in rows(
        graph_v1,
        f"MATCH (m:Metabolite) WHERE m.source = '{SOURCE}' "
        f"RETURN m.{MICROBE_RELATION_COUNT} AS n",
    ):
        assert row["n"] in (None, "")
    # And the edge count is still zero, which is the finding both releases make.
    assert "PRODUCES edges from MiMeDB: 0" in out_v1


