def test_a_legacy_five_digit_accession_still_finds_its_node(graph, csv_dir):
    """HMDB widened its accessions from five digits to seven in 2018 and
    MiMeDB's column holds both spellings. A literal string join misses every
    legacy id **silently**, which reads as "MiMeDB has no HMDB id for this
    compound" — and then mints a second node for it."""
    assert normalise_hmdb_id("HMDB00011") == "HMDB0000011"
    assert normalise_hmdb_id("HMDB0000011") == "HMDB0000011"
    assert normalise_hmdb_id("NULL") == ""
    assert normalise_hmdb_id("CHEBI:30772") == ""
    assert not rows(graph, "MATCH (m:Metabolite {title: 'Butyrate salt'}) RETURN m")
    reason = [r for r in table(csv_dir, "unresolved_mimedb.csv")
              if r["name"] == "Butyrate salt"]
    assert len(reason) == 1
    assert reason[0]["metabolite_id"] and "already holds" in reason[0]["reason"]


def test_a_compound_held_under_another_name_is_found_by_its_structure(graph, csv_dir):
    """`Ethanoic acid` and `Acetic acid` are one compound with two names, and
    only the InChIKey says so. Without the structural test this record becomes
    a second acetate node — and NJC19, which tries derived spellings in order,
    can then reach the new one while HMDB's producers stay on the old."""
    assert not rows(graph, "MATCH (m:Metabolite {title: 'Ethanoic acid'}) RETURN m")
    reason = [r for r in table(csv_dir, "unresolved_mimedb.csv")
              if r["name"] == "Ethanoic acid"]
    assert len(reason) == 1 and "already holds" in reason[0]["reason"]


def test_a_contested_hmdb_accession_is_not_a_join_key(graph, csv_dir):
    """149 accessions in the real file are claimed by two MiMeDB records each,
    almost all of them a D-/L- enantiomer pair. Joining on one folds two
    compounds into one node and attributes each one's annotations to the other,
    so both records keep their own identity and the ledger says why — the same
    rule `reconcile` applies to an ambiguous organism name."""
    ids = {
        r["title"]: r["id"]
        for r in rows(
            graph,
            "MATCH (m:Metabolite) WHERE m.title IN ['L-Tyrosine', 'D-Tyrosine'] "
            "RETURN m.title AS title, m.id AS id",
        )
    }
    assert set(ids) == {"L-Tyrosine", "D-Tyrosine"}
    assert ids["L-Tyrosine"] != ids["D-Tyrosine"]
    assert all(i.startswith("MIMEDB:") for i in ids.values())
    contested = [r for r in table(csv_dir, "unresolved_mimedb.csv")
                 if "is claimed by" in r["reason"]]
    assert len(contested) == CONTESTED_RECORDS
    assert all("HMDB0000158" in r["reason"] for r in contested)
    # And neither of them kept the accession, because it did not identify them.
    for row in rows(
        graph,
        "MATCH (m:Metabolite) WHERE m.title IN ['L-Tyrosine', 'D-Tyrosine'] "
        "RETURN m.hmdb_id AS hmdb_id",
    ):
        assert not row["hmdb_id"]


def test_an_already_held_compound_is_a_ledger_row_and_not_a_merge(graph, csv_dir, prep_output):
    """`Writer` keys `metabolite.csv` on `metabolite_id` and the first row per
    key wins, so a MiMeDB row written for a compound HMDB already has would
    have its properties silently discarded — an outcome that reads like a
    successful join in the row count and is not one. Ledgering it makes
    "MiMeDB added nothing here" a number."""
    assert f"already has a node: {ALREADY_HELD}" in prep_output
    ledger = table(csv_dir, "unresolved_mimedb.csv")
    assert len(ledger) == LEDGER_ROWS
    assert all(r["source"] == SOURCE for r in ledger)
    held = [r for r in ledger if "already holds" in r["reason"]]
    assert len(held) == ALREADY_HELD
    assert all(r["metabolite_id"] for r in held), "a ledger row names the node that won"


