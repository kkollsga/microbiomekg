"""MiMeDB: a source that writes no edge, and the four ways it could have written
a wrong one.

The headline assertion in this module is a **zero** —
:func:`test_mimedb_writes_no_taxon_metabolite_edge_because_there_is_none`. The
downloads on disk are two MySQL tables with no join between them, so the
per-taxon production edge D5 has been waiting for is not derivable from them,
and the loader says so with a count rather than by omission. Everything else
here is about identity: this source's whole contribution is giving NJC19's
free-text compounds something with an InChIKey to point at, and every way of
getting that wrong produces a *second node for one compound*, which halves the
evidence D6 computes over.

The fixture is ``tests/fixtures/mimedb_mini/``, generated by
``tests/fixtures/make_mimedb_mini.py``, which names every record and its trap.
"""

