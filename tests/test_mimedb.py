def test_only_the_selected_slice_is_loaded(graph, prep_output):
    """44% of the real file is glycerophospholipids. A loader that kept
    everything would put a lipidomics table in a microbiome graph, and the
    count is the assertion rather than "it built"."""
    loaded = one(
        graph, f"MATCH (m:Metabolite) WHERE m.source = '{SOURCE}' RETURN count(m) AS n"
    )["n"]
    assert loaded == LOADED
    assert f"skipped {NOT_SELECTED} that no rule selected" in prep_output
    assert not rows(graph, "MATCH (m:Metabolite {title: 'PC(16:0/18:1)'}) RETURN m")


def test_each_selection_rule_is_recorded_on_the_node_it_kept(graph):
    """A rule described only in a docstring cannot be audited and cannot be
    changed safely."""
    kept = {
        rule
        for r in rows(
            graph,
            f"MATCH (m:Metabolite) WHERE m.source = '{SOURCE}' "
            "RETURN DISTINCT m.selection_rule AS rule",
        )
        for rule in r["rule"].split("|")
    }
    assert kept <= set(SELECTION_RULES)
    assert kept == {"observed", "origin-classified", "njc19-compound"}


def test_the_njc19_rule_selects_a_compound_njc19_needs_and_not_one_it_might(graph):
    """`Pectin` is in NJC19's fixture and no HMDB record holds it, so this
    record is what turns a minted stub into an identified compound. `Chitin` is
    the same *shape* of record and NJC19 never names it, so it is not loaded:
    the rule is "a compound NJC19 needs", not "a compound like the ones it
    needs"."""
    pectin = one(graph, "MATCH (m:Metabolite {title: 'Pectin'}) RETURN m.selection_rule AS r")
    assert pectin["r"] == "njc19-compound"
    assert not rows(graph, "MATCH (m:Metabolite {title: 'Chitin'}) RETURN m")


