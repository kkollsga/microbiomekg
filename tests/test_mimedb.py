def run(script, *args):
    return run_prep(script, *args)


def build(work: Path, release: str) -> tuple[object, Path, str]:
    """HMDB then MiMeDB through their real preps, then the real blueprint.

    HMDB first because that is the declared order (`DEPENDS_ON = ["hmdb"]`):
    every "already held" test in this module is a test of what MiMeDB does when
    a node exists, and with no HMDB there is nothing to hold anything.
    """
    csv_dir = work / "csv"
    csv_dir.mkdir(parents=True, exist_ok=True)

    run(
        PREPS_DIR / "prep_hmdb.py",
        "--xml",
        str(HMDB_MINI),
        "--taxdump",
        str(TAXDUMP_MINI),
        "--reactome",
        str(REACTOME_MINI),
        "--out",
        str(csv_dir),
    )
    prep = run(
        PREP,
        "--metabolites",
        str(MIMEDB_MINI / f"mimedb_metabolites_{release}.csv"),
        "--microbes",
        str(MIMEDB_MINI / f"mimedb_microbes_{release}.csv"),
        "--njc19",
        str(NJC19_MINI),
        "--taxdump",
        str(TAXDUMP_MINI),
        "--out",
        str(csv_dir),
    )
    run(
        PREPS_DIR / "prep_reactome.py",
        "--reactome",
        str(REACTOME_MINI),
        "--out",
        str(csv_dir),
    )
    run(
        PREPS_DIR / "prep_taxonomy.py",
        "--taxdump",
        str(TAXDUMP_MINI),
        "--out",
        str(csv_dir),
        "--scope",
        "cited",
        "--cited-from",
        str(csv_dir / "cited_taxa.csv"),
    )

    sources = [SOURCE, "hmdb", "reactome"]
    return load_from_csv_dir(csv_dir, sources), csv_dir, prep.stdout


