def test_a_mimedb_node_carries_no_invented_detection_status(graph):
    """`status` is HMDB's four-value vocabulary and this file has no such
    column. Writing a plausible value into a column another source's evidence
    rule reads would be inventing evidence; `mimedb_origin` carries what this
    file does grade on."""
    for row in rows(
        graph,
        f"MATCH (m:Metabolite) WHERE m.source = '{SOURCE}' "
        "RETURN m.status AS status, m.microbial_origin AS origin, "
        "m.mimedb_id AS mimedb_id, m.inchikey AS inchikey",
    ):
        assert not row["status"]
        assert row["origin"] is False
        assert row["mimedb_id"].startswith("MMDBc")
        assert row["inchikey"]


def test_the_null_string_never_reaches_the_graph(graph):
    """The MySQL dump writes an absent value as the four characters `NULL`.
    Read straight that is the *string* "NULL" in a CSV column, which kglite
    loads as a value and `ontology_audit()` counts as present — a filled
    field that says nothing."""
    row = one(
        graph,
        "MATCH (m:Metabolite {title: 'NULL-valued compound'}) "
        "RETURN m.cas AS cas, m.chemical_formula AS formula, m.hmdb_id AS hmdb_id",
    )
    assert not row["cas"] and not row["formula"] and not row["hmdb_id"]
    assert not rows(graph, "MATCH (m:Metabolite) WHERE m.cas = 'NULL' RETURN m")


def test_the_origin_axis_survives_onto_the_node(graph):
    """`metabolite_type` is the one thing the research document found MiMeDB
    grades on an evidence basis, and it is 97.4% empty in the real file — which
    is a fact about the source that only survives if the column is loaded."""
    origins = {
        r["origin"]
        for r in rows(
            graph,
            f"MATCH (m:Metabolite) WHERE m.source = '{SOURCE}' AND m.mimedb_origin <> '' "
            "RETURN DISTINCT m.mimedb_origin AS origin",
        )
    }
    assert origins == {"Co-metabolite", "Primary"}


def test_the_prep_reports_what_it_did_not_load(prep_output):
    for phrase in ("selection rule:", "that no rule selected",
                   "not written because the compound already has a node:",
                   "so not used as a join key:", "mimedb_origin:",
                   "PRODUCES edges from MiMeDB: 0"):
        assert phrase in prep_output


def test_every_record_is_a_node_or_a_counted_reason(prep_output, csv_dir):
    """Input records = loaded + not selected + ledger rows. A silent drop
    cannot hide in the difference."""
    ledger = table(csv_dir, "unresolved_mimedb.csv")
    # The two contested records are ledgered *and* loaded — the ledger row is
    # about the accession they lost, not about the record being dropped.
    assert LOADED + NOT_SELECTED + ALREADY_HELD == RECORDS
    assert len(ledger) == ALREADY_HELD + CONTESTED_RECORDS


@pytest.mark.fixture
def test_the_fixture_keeps_the_real_dumps_columns():
    """A fixture with a trimmed header would hide a column-name typo in the
    loader: every field this prep reads is addressed by name."""
    with (MIMEDB_MINI / "mimedb_metabolites_v1.csv").open(encoding="utf-8") as fh:
        columns = next(csv.reader(fh))
    assert len(columns) == 42
    assert columns[:3] == ["id", "name", "mime_id"]
    assert {"hmdb_id", "detected", "quantified", "metabolite_type", "moldb_inchikey",
            "moldb_formula", "moldb_average_mass", "cas"} <= set(columns)

    with (MIMEDB_MINI / "mimedb_microbes_v1.csv").open(encoding="utf-8") as fh:
        columns = next(csv.reader(fh))
    assert len(columns) == 39
    assert {"ncbi_tax_id", "activity", "species", "strain"} <= set(columns)
    # And nothing in either header names the other table.
    assert not {c for c in columns if "metabolite" in c}
