def test_mimedb_writes_no_taxon_metabolite_edge_because_there_is_none(
    graph, prep_output
):
    """**The headline assertion of this module, and it is a zero.**

    Both downloads are `SELECT * FROM microbes` and `SELECT * FROM metabolites`;
    the join between them is in neither, in **v1.0 and in v2.0 alike**. The
    nearest thing to a relation in either is a `microbes.activity` column that
    says `Production (export)` or `Consumption (import)` **with no compound
    named anywhere on the row**. Deriving an edge from it would manufacture
    exactly the claim D5 asks for out of a field that does not make it. The
    fixture carries one row of each on purpose.

    A zero is only worth asserting if something could make it non-zero, and
    something could: this test fails the moment any relationship is declared
    for this source, which is the review gate on "MiMeDB finally has an edge
    list" being a deliberate change rather than an accident."""
    assert RELATIONSHIPS == {}
    for row in rows(
        graph, "MATCH ()-[r]->() RETURN DISTINCT r.primary_source AS source"
    ):
        assert row["source"] != SOURCE
    assert "PRODUCES edges from MiMeDB: 0" in prep_output
    # And the zero is stated against the release actually read, so a future v3
    # cannot inherit v2's finding by silence.
    assert "v2.0" in prep_output


def test_the_relation_count_column_is_a_count_and_never_an_edge(graph, prep_output):
    """v2.0's `microbe_relations` is the closest MiMeDB has ever come to
    publishing the association, and it still is not one: an integer per
    metabolite, no microbe id anywhere in the file. It rides on the node under a
    name that cannot be read as an edge count — a node property called
    `microbe_relations` beside a graph with zero MiMeDB edges is a trap — and
    the count is what makes "MiMeDB knows these pairs and does not publish them"
    a number.

    Acetic acid's real value is 2,537. The fixture carries it verbatim, and no
    edge in this graph corresponds to any of them."""
    assert MICROBE_RELATION_COUNT == "mimedb_microbe_relation_count"
    counts = {
        r["title"]: r["n"]
        for r in rows(
            graph,
            f"MATCH (m:Metabolite) WHERE m.source = '{SOURCE}' "
            f"RETURN m.title AS title, m.{MICROBE_RELATION_COUNT} AS n",
        )
    }
    assert counts["Trimethylamine oxide"] == 146
    assert all(isinstance(n, int) for n in counts.values() if n is not None)
    # Zero is a value MiMeDB states, not an absence.
    assert (
        counts["Ethanoic acid" if "Ethanoic acid" in counts else "Pectin"] is not None
    )
    total = sum(n for n in counts.values() if n is not None)
    assert (
        f"microbe_relations: {total:,} taxon-metabolite pairs counted, 0 enumerated"
        in prep_output
    )


def test_an_absent_relation_count_is_empty_and_not_a_zero(graph):
    """`NULL-valued compound` leaves every optional column at the dump's literal
    `NULL`, `microbe_relations` included. Mapping that to `0` would state
    "MiMeDB relates this compound to no microbe", which is a measurement the
    file does not make — the same error as writing a `status` this source has
    no column for."""
    row = one(
        graph,
        "MATCH (m:Metabolite {title: 'NULL-valued compound'}) "
        f"RETURN m.{MICROBE_RELATION_COUNT} AS n",
    )
    assert row["n"] in (None, ""), f"an absent count arrived as {row['n']!r}"


def test_the_organisms_are_read_reported_and_not_loaded(graph, prep_output):
    """The microbes table resolves almost perfectly — nearly every row carries an
    NCBI taxid — and that is exactly the point: this source has the taxon side
    of D5's edge and nothing to attach it to. Reporting the number is what
    separates "MiMeDB does not close D5" from "MiMeDB has nothing"; loading it
    would put 2,648 unconnected `Taxon` nodes in the real graph."""
    assert (
        f"microbes: {MICROBES} organisms, {MICROBES_WITH_TAXID} with an NCBI taxid"
        in prep_output
    )
    assert "promoted 1" in prep_output, (
        "the strain-level row must promote to its species"
    )
    # Not in cited_taxa.csv, so the taxonomy build keeps none of them for MiMeDB.
    assert not rows(
        graph,
        f"MATCH (t:Taxon)-[r]->() WHERE r.primary_source = '{SOURCE}' RETURN t",
    )


def test_the_activity_column_is_reported_and_never_loaded(graph, prep_output):
    """115 rows of the real v2 microbes table say `Production (export)` or
    `Consumption (import)` and name **no compound**. They are counted in the
    report and land nowhere else: not an edge, and not a `Taxon` property
    either. A `mimedb_activity = 'Production (export)'` on a taxon is a
    production claim with no object, and D5 is the query that would read it as
    one — see `docs/model.md`.

    The graph therefore carries the string nowhere at all."""
    assert "activity: 1 Production (export), 1 Consumption (import)" in prep_output
    assert "names no compound" in prep_output
    assert not rows(
        graph,
        "MATCH (n) WHERE any(k IN keys(n) WHERE k CONTAINS 'activity') RETURN n LIMIT 1",
    )


