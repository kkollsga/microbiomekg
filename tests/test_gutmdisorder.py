"""gutMDisorder: the second source, and the pitfalls that make it one.

Every assertion here is a *failure mode first*. The fixture
(``tests/fixtures/gutmdisorder_mini/``, generated by
``tests/fixtures/make_gutmdisorder_mini.py``, which names every injected row)
carries one row per trap from ``docs/research/source-formats.md`` §1, and the
loader is measured against what each trap would silently do:

* an index of ``1.9999999999999`` truncated by ``int()`` lands on study **1**,
  a different paper;
* an index of ``2.5`` rounded lands on study 2 or 3 — one of them wrong;
* a duplicate row counted twice inflates the evidence for a claim;
* a both-direction pair collapsed to one edge resolves a disagreement by
  majority, which G4 forbids;
* a deleted taxid dropped removes an observation and leaves no trace;
* a merged taxid kept as given splits one organism into two nodes.

The second half of the module is what the *second source* is for: a paper, a
disease and a taxon cited by both sources have to be one node each, or the
graph is two graphs in one file.
"""

