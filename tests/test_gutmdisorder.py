def test_an_exact_duplicate_is_one_edge_that_says_it_was_repeated(graph):
    """Two identical curated rows are one fact stated twice, not two
    independent observations — counting them twice would inflate the evidence
    for the claim. The count survives as `duplicate_rows` so nothing is lost."""
    result = one(
        graph,
        "MATCH (t:Taxon {id: 816})-[r:ASSOCIATED_WITH]->(d:Disease {id: 'MONDO:0011122'}) "
        "WHERE r.primary_source = 'gutmdisorder' "
        "RETURN count(r) AS edges, sum(r.duplicate_rows) AS rows_behind_them",
    )
    assert result["edges"] == 1
    assert result["rows_behind_them"] == 2


def test_a_both_direction_pair_stays_two_edges(graph):
    """G4: a pair carrying both directions is returned as two rows with their
    evidence, never reduced to a sign and never resolved by majority."""
    result = rows(
        graph,
        "MATCH (t:Taxon {id: 838})-[r:ASSOCIATED_WITH]->(d:Disease {id: 'MONDO:0011122'}) "
        "WHERE r.primary_source = 'gutmdisorder' "
        "RETURN r.direction AS direction, r.source_relation AS relation",
    )
    assert sorted(r["direction"] for r in result) == ["decreased", "increased"]
    # The source's own sentence is what distinguishes them, and it is kept.
    assert len({r["relation"] for r in result}) == 2


def test_the_duplicate_count_is_one_where_nothing_was_duplicated(graph):
    """A `duplicate_rows` that is silently null on the normal case would make
    the property unusable in a filter."""
    result = one(
        graph,
        "MATCH ()-[r:ASSOCIATED_WITH]->() WHERE r.primary_source = 'gutmdisorder' "
        "RETURN count(r) AS edges, "
        "sum(CASE WHEN r.duplicate_rows IS NULL THEN 1 ELSE 0 END) AS missing",
    )
    assert result["edges"] == GUTMD_ASSOCIATED_WITH
    assert result["missing"] == 0


