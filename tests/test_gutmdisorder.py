@pytest.mark.parametrize(
    "value, expected",
    [
        (2, 2),
        (2.0, 2),
        (1.9999999999999, 2),      # the real mouse noise
        (3.0000000000001, 3),      # and the other direction
        (33.9999999999999, 34),    # source-formats.md's worked example
    ],
)
def test_binary_noise_rounds_to_the_index_it_means(value, expected):
    assert study_index(value) == expected


def test_truncation_is_the_bug_this_replaces():
    """``int()`` does not merely lose a row — it files it under a different
    study. 33.9999999999999 becomes 33, and that association is then attributed
    to somebody else's paper with no warning anywhere."""
    assert int(33.9999999999999) == 33
    assert study_index(33.9999999999999) == 34


@pytest.mark.parametrize("value", [2.5, 2.1, "", None, float("nan"), "two"])
def test_a_value_that_is_not_an_integer_is_rejected_not_rounded(value):
    """2.5 is equidistant from two studies and 2.1 is simply not a study
    number. There is no honest way to pick, so the row is reported."""
    assert study_index(value) is None


