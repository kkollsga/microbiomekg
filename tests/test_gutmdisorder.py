def test_every_association_row_is_accounted_for(graph, csv_dir, prep_output):
    """Input rows = edges + ledger records + explicitly reported collapses.
    The point of the rule is that a silent drop cannot hide in the difference."""
    edges = one(
        graph,
        "MATCH ()-[r:ASSOCIATED_WITH]->() WHERE r.primary_source = 'gutmdisorder' "
        "RETURN count(DISTINCT r.source_record_id + '|' + r.direction) AS n",
    )["n"]
    intervention_only = 1  # study 234's taxa reach both endpoints; only its rows
    ledger = table(csv_dir, "unresolved_associations.csv")
    assert len(ledger) == GUTMD_LEDGER_ROWS
    # One edge per surviving row; a row reaching two diseases is still one row.
    surviving = ASSOCIATION_ROWS - EXACT_DUPLICATES - len(ledger)
    assert edges + intervention_only == surviving + 1  # mouse-3's rows are intervention+disease
    assert f"{EXACT_DUPLICATES} exact duplicates collapsed" in prep_output


